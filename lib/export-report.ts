/**
 * Benchmark Report Generator (Markdown & JSON export)
 */

import { ComparisonResult } from "./rag-pipelines";

export function generateMarkdownReport(data: ComparisonResult, activeDocName: string): string {
  const { query, timestamp, naive, jevGated, summary } = data;
  const isBlocked = jevGated.shortCircuited;

  return `# JevRAG Workbench — Side-by-Side Evaluation Audit Report

**Generated At:** ${timestamp}  
**Active Document:** ${activeDocName}  
**Query:** "${query}"  

---

## ⚡ Executive Summary

| Metric | Track A: Naive Vector RAG | Track B: 3-Stage Jev-Gated RAG | Delta / Advantage |
| :--- | :--- | :--- | :--- |
| **Chunks Sent to LLM** | ${naive.chunksUsed} chunks | ${isBlocked ? "0 (Blocked)" : `${jevGated.chunksUsed} chunks`} | **${isBlocked ? "100% LLM Chunks Bypassed" : `Dropped ${15 - jevGated.chunksUsed} noise chunks`}** |
| **Prompt Tokens** | ${naive.inputTokens} tok | ${jevGated.inputTokens} tok | **${jevGated.promptTokensSaved} tok saved (+${jevGated.tokenSavingsPercent}%)** |
| **Sufficiency Gate** | Bypassed (Stuffed) | ${isBlocked ? `BLOCKED (${(jevGated.telemetry.stage3.sufficiencyProbability * 100).toFixed(0)}% < ${(jevGated.telemetry.stage3.threshold * 100).toFixed(0)}%)` : `PASSED (${(jevGated.telemetry.stage3.sufficiencyProbability * 100).toFixed(0)}%)`} | **${isBlocked ? "Hallucination Prevented with 0 LLM Tokens" : "Evidence Verified Factually"}** |
| **Contradiction Preservation** | Ignored | ${jevGated.contradictionPreserved ? "ACTIVE (Premise Corrected)" : "N/A"} | **${jevGated.contradictionPreserved ? "Preserved refutation chunk over similarity" : "Standard Pass"}** |
| **Query Latency** | ${naive.latencyMs}ms | ${jevGated.latencyMs.totalMs}ms | Jev decision: ${jevGated.latencyMs.stage1RouterMs + jevGated.latencyMs.stage2FilterMs + jevGated.latencyMs.stage3SufficiencyMs}ms |
| **Estimated Cost** | \$${naive.estimatedCostUsd.toFixed(5)} | \$${jevGated.costs.totalCostUsd.toFixed(5)} | **-${jevGated.costSavingsPercent}% net cost** |

---

## 🔬 Split-Screen Output Comparison

### Track A: Naive Vector RAG (Top-15 Context Stuffing)
${naive.hallucinationRisk === "HIGH" ? "> ⚠️ **Vulnerability Detected:** Stuffed noisy context caused LLM to hallucinate or adopt false premise.\n" : ""}
\`\`\`
${naive.answer}
\`\`\`

### Track B: 3-Stage Jev-Gated Modular RAG
${isBlocked ? "> ⛔ **Blocked by Sufficiency Gate:** Generator LLM was aborted immediately. Zero hallucinated tokens generated.\n" : ""}
\`\`\`
${jevGated.answer}
\`\`\`

---

## 🔍 Jev System One Decision Trace

### Stage 1: Pre-Retrieval Router (Choice + Noul)
- **Intent Classification:** \`${jevGated.telemetry.stage1.intent}\` (Confidence: ${(jevGated.telemetry.stage1.rawConfidence * 100).toFixed(0)}%)
- **Ambiguity Probability (Noul):** ${(jevGated.telemetry.stage1.ambiguityProbability * 100).toFixed(1)}%
- **Decision:** ${jevGated.telemetry.stage1.intent === "needs_docs" ? "Proceed to Vector Search" : "Short-circuit: Chitchat / Out of scope"}

### Stage 2: Parallel Filter & Rerank Matrix
- **Surviving Chunks Kept:** ${jevGated.telemetry.survivingChunks.length} of 15
- **Contradiction Gate:** ${jevGated.contradictionPreserved ? "Triggered (preserved chunk contradicting user premise)" : "None"}

| Chunk ID | Cosine Sim | Jev Utility | Contradiction Prob | Composite Score | Status | Reason |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
${jevGated.telemetry.stage2Evaluations
  .map(
    (e) =>
      `| **${e.chunkId}** | ${(e.vectorSimilarity * 100).toFixed(1)}% | ${(e.answerUtilityScore * 100).toFixed(0)}% | ${(e.contradictsPremiseProbability * 100).toFixed(0)}% | ${e.compositeScore.toFixed(3)} | **${e.status}** | ${e.reason} |`
  )
  .join("\n")}

### Stage 3: Sufficiency Gate (Noul)
- **Sufficiency Probability:** ${(jevGated.telemetry.stage3.sufficiencyProbability * 100).toFixed(1)}%
- **Threshold:** ${(jevGated.telemetry.stage3.threshold * 100).toFixed(0)}%
- **Outcome:** ${isBlocked ? "BLOCKED (Short-circuited with 0 LLM calls)" : "PASSED (Clean citation generation)"}
- **Explanation:** ${jevGated.telemetry.stage3.reason}

---
*Report generated by JevRAG Workbench — TypeSafe AI System One Evaluator.*
`;
}

export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
